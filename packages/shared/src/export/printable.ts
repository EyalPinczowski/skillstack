import { parseLocalDate, weekday, WEEKDAY_NAMES } from '../dates';
import type { Task } from '../schemas';
import { TASK_TYPE_LABEL } from '../labels';
import type { ScheduleResult } from '../scheduling/engine';

/**
 * A printable, self-contained HTML schedule (one section per study day, with a tick box per
 * block), and a CSV log template to record actual hours until the app does it (spec 3.6).
 */

const MONTHS = [
  'January',
  'February',
  'March',
  'April',
  'May',
  'June',
  'July',
  'August',
  'September',
  'October',
  'November',
  'December',
];

/** Task-type colours from the chosen "Blocks" design (light theme), each with a text label. */
const TYPE_COLOR: Record<Task['type'], string> = {
  course: '#2456C4',
  cert_exam: '#A04500',
  practice: '#6A3DB5',
  admin: '#4F5866',
  cv_update: '#1F6F4A',
};

export function longDate(date: string): string {
  const { year, month, day } = parseLocalDate(date);
  return `${WEEKDAY_NAMES[weekday(date)]}, ${day} ${MONTHS[month - 1]} ${year}`;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

const hours = (minutes: number) => `${Math.round((minutes / 60) * 100) / 100} h`;

export function scheduleToHtml(
  result: ScheduleResult,
  tasks: Task[],
  options: { title: string; subtitle?: string; warnings?: string[] },
): string {
  const byId = new Map(tasks.map((t) => [t.id, t]));
  const studyDays = result.days.filter((d) => d.blocks.length > 0);
  const total = result.blocks.reduce((s, b) => s + b.minutes, 0);

  const sections = studyDays
    .map((day) => {
      const rows = day.blocks
        .map((b) => {
          const task = byId.get(b.taskId);
          const type = task?.type ?? 'course';
          const label =
            b.kind === 'anchor' ? `${TASK_TYPE_LABEL[type]} · fixed time` : TASK_TYPE_LABEL[type];
          return `<tr>
  <td class="time">${b.start}–${b.end}</td>
  <td class="task" style="border-left-color:${TYPE_COLOR[type]}">${escapeHtml(task?.title ?? b.taskId)}</td>
  <td class="type" style="color:${TYPE_COLOR[type]}">${label}</td>
  <td class="hrs">${hours(b.minutes)}</td>
  <td class="tick"><span class="box" aria-label="done"></span></td>
</tr>`;
        })
        .join('\n');
      return `<section>
<h2>${longDate(day.date)} <span>${hours(day.scheduledMinutes)} of ${hours(day.capacityMinutes)}</span></h2>
<table>
<thead><tr><th>Time</th><th>Task</th><th>Type</th><th>Hours</th><th>Done</th></tr></thead>
<tbody>
${rows}
</tbody>
</table>
</section>`;
    })
    .join('\n');

  const warningList = options.warnings?.length
    ? `<div class="warn"><strong>Check before you start:</strong><ul>${options.warnings
        .map((w) => `<li>${escapeHtml(w)}</li>`)
        .join('')}</ul></div>`
    : '';

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${escapeHtml(options.title)}</title>
<style>
  :root { color-scheme: light; }
  body { font-family: "Atkinson Hyperlegible", system-ui, -apple-system, "Segoe UI", sans-serif; color: #161A22; background: #FFFFFF; margin: 24px; line-height: 1.4; }
  h1 { font-size: 24px; margin: 0 0 4px; }
  .sub { color: #525A68; margin: 0 0 16px; }
  section { break-inside: avoid; margin: 0 0 18px; }
  h2 { font-size: 16px; margin: 0 0 6px; display: flex; justify-content: space-between; border-bottom: 2px solid #3546C9; padding-bottom: 4px; }
  h2 span { color: #525A68; font-weight: normal; font-size: 14px; }
  table { width: 100%; border-collapse: collapse; font-size: 14px; }
  th { text-align: left; color: #525A68; font-weight: 600; padding: 4px 6px; border-bottom: 1px solid #D3D8E0; }
  td { padding: 5px 6px; border-bottom: 1px solid #EBEDF2; vertical-align: top; }
  td.time, td.hrs { white-space: nowrap; font-variant-numeric: tabular-nums; }
  td.task { border-left: 4px solid; }
  td.type { white-space: nowrap; font-weight: 700; }
  .box { display: inline-block; width: 16px; height: 16px; border: 2px solid #525A68; border-radius: 3px; }
  .warn { border: 2px solid #A04500; background: #FCEADB; padding: 10px 14px; border-radius: 8px; margin: 0 0 16px; }
  .warn ul { margin: 6px 0 0; padding-left: 20px; }
  footer { color: #525A68; font-size: 12px; margin-top: 24px; }
  @media print { body { margin: 12mm; } @page { size: A4; margin: 10mm; } }
</style>
</head>
<body>
<h1>${escapeHtml(options.title)}</h1>
<p class="sub">${escapeHtml(options.subtitle ?? '')} ${studyDays.length} study days · ${hours(total)} planned${result.finishDate ? ` · finish ${longDate(result.finishDate)}` : ''}</p>
${warningList}
${sections}
<footer>Generated by the Skillstack scheduling engine. Hours are estimates – log what actually happens so the plan can adjust.</footer>
</body>
</html>
`;
}

function csvCell(value: string | number): string {
  // Text that starts like a formula gets a leading quote so spreadsheets show it as text.
  const s = typeof value === 'string' && /^[=+\-@\t\r]/.test(value) ? `'${value}` : String(value);
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** One row per task per day, with empty columns for actual hours, status and a note. */
export function logTemplateCsv(result: ScheduleResult, tasks: Task[]): string {
  const byId = new Map(tasks.map((t) => [t.id, t]));
  const rows: (string | number)[][] = [
    ['date', 'task_id', 'task', 'type', 'planned_hours', 'actual_hours', 'status', 'note'],
  ];
  for (const day of result.days) {
    const perTask = new Map<string, number>();
    for (const b of day.blocks) perTask.set(b.taskId, (perTask.get(b.taskId) ?? 0) + b.minutes);
    for (const [taskId, minutes] of perTask) {
      const task = byId.get(taskId);
      rows.push([
        day.date,
        taskId,
        task?.title ?? taskId,
        task?.type ?? '',
        Math.round((minutes / 60) * 100) / 100,
        '',
        '',
        '',
      ]);
    }
  }
  return rows.map((r) => r.map(csvCell).join(',')).join('\n') + '\n';
}
